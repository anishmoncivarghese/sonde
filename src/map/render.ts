// Transitive reach, the thing a sorted table and a one-hop highlight both fail
// to give: asked what breaks when a module changes, the answer is the closure.
function reachable(seedPath, direction) {
  const next = new Map();
  for (const { e } of edgeEls) {
    if (!shown(e)) continue;
    const from = direction === "downstream" ? e.from : e.to;
    const to = direction === "downstream" ? e.to : e.from;
    next.set(from, (next.get(from) || []).concat(to));
  }
  const seen = new Set(), queue = [seedPath];
  while (queue.length) {
    for (const t of next.get(queue.shift()) || []) {
      if (!seen.has(t)) { seen.add(t); queue.push(t); }
    }
  }
  seen.delete(seedPath);
  return seen;
}

