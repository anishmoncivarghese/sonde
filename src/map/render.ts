import type { MapModel } from "./model.js";

export interface MapStamp {
  revision: string | null;
  dirty: boolean | null;
  driftedFiles: number;
  excludedTestModules: number;
  resolvedReferences: number;
  heuristicReferences: number;
  missingTsConfig: boolean;
}

export const MAP_MARKER = "<!-- generated by sonde map -->";

function escapeJson(value: unknown): string {
  // The payload is embedded in a <script> element, so a literal "</script>" in
  // a module path or symbol name would close it early. Escaping the angle
  // brackets is enough and keeps the JSON valid.
  return JSON.stringify(value)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

